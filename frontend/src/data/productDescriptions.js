/**
 * Returns a concise, tailored short description (12–24 words).
 * Ideal for ProductCard, QuickViewModal, and Infinity AI recommendation chips.
 */
export function getProductShortDescription(product) {
  if (!product) return '';
  const id = product._id || product.id;
  if (id && PRODUCT_DESCRIPTIONS[id]?.short) {
    return PRODUCT_DESCRIPTIONS[id].short;
  }
  if (product.shortDescription) return product.shortDescription;
  if (product.description) {
    const firstSentence = product.description.split(/\.\s+/)[0];
    return firstSentence.endsWith('.') ? firstSentence : `${firstSentence}.`;
  }
  return 'Personalized keepsake made to order around your favourite photos and moments.';
}

/**
 * Returns a detailed full description (35–50 words).
 * Ideal for the full Product Details page.
 */
export function getProductFullDescription(product) {
  if (!product) return '';
  const id = product._id || product.id;
  if (id && PRODUCT_DESCRIPTIONS[id]?.full) {
    return PRODUCT_DESCRIPTIONS[id].full;
  }
  return product.description || getProductShortDescription(product);
}
